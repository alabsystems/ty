/// STRETCH — `K2_ite_disjunctive` (K2_ite_disjunctive.clean): an IF-update equals its
/// disjunctive expansion:
///
/// ```text
/// (c : Bool) -> (a b v : Nat)
/// -> Iff (@Eq Nat v (if c then a else b))
///        (Or (And (@Eq Bool c true) (@Eq Nat v a)) (And (@Eq Bool c false) (@Eq Nat v b)))
/// ```
///
/// The `if c then a else b` sugar is pinned as its standard desugaring
/// `@ite.{1} Nat (@Eq Bool c Bool.true) (instDecidableEqBool c Bool.true) a b` — the
/// Decidable-instance form is part of the pinned statement. The pin spells the boolean
/// literals `Bool.true`/`Bool.false`; the prelude's bare `true`/`false` aliases are
/// definitionally the same, which is exactly what `is_def_eq` certifies.
fn pin_k2_ite_disjunctive() -> Expr {
    pi(
        bool_(), // c
        pi(
            nat(), // a
            pi(
                nat(), // b
                pi(
                    nat(), // v
                    iff(
                        eq1(
                            nat(),
                            v(0), // v
                            apps(
                                cl("ite", vec![l1()]),
                                [
                                    nat(),
                                    eq1(bool_(), v(3), cn("Bool.true")),
                                    apps(cn("instDecidableEqBool"), [v(3), cn("Bool.true")]),
                                    v(2), // a
                                    v(1), // b
                                ],
                            ),
                        ),
                        or(
                            and(eq1(bool_(), v(3), cn("Bool.true")), eq1(nat(), v(0), v(2))),
                            and(eq1(bool_(), v(3), cn("Bool.false")), eq1(nat(), v(0), v(1))),
                        ),
                    ),
                ),
            ),
        ),
    )
}

