/// THE PIN CHECK: every registered statement must be definitionally equal to its hand-built,
/// elaborator-free pin. A failure prints BOTH exprs (pin then registered) for diagnosis.
#[test]
fn statement_pins_hold() {
    let envs = load_all_envs();
    let mut failures: Vec<String> = Vec::new();
    let mut pinned_statements = 0usize;
    let mut pinned_aux = 0usize;
    let mut flagships_unpinned: Vec<&str> = Vec::new();

    for spec in PINS {
        let env = &envs[spec.file];
        let Some(c) = env.get_const(&Name::from_string(spec.name)) else {
            failures.push(format!(
                "{}: constant `{}` did not register",
                spec.file, spec.name
            ));
            if spec.kind == Kind::Flagship {
                flagships_unpinned.push(spec.name);
            }
            continue;
        };
        // Statements here are all level-monomorphic; a level-parametric registration would
        // make the concrete-level pin silently vacuous, so reject it loudly.
        if !c.level_params.is_empty() {
            failures.push(format!(
                "{}: `{}` registered with unexpected level params {:?}",
                spec.file, spec.name, c.level_params
            ));
            if spec.kind == Kind::Flagship {
                flagships_unpinned.push(spec.name);
            }
            continue;
        }
        let pin = (spec.build)();
        if TypeChecker::new(env).is_def_eq(&pin, &c.type_) {
            match spec.kind {
                Kind::Aux => {
                    pinned_aux += 1;
                    println!("PINNED (aux): {} [{}]", spec.name, spec.file);
                }
                _ => {
                    pinned_statements += 1;
                    println!("PINNED: {} [{}]", spec.name, spec.file);
                }
            }
        } else {
            if spec.kind == Kind::Flagship {
                flagships_unpinned.push(spec.name);
            }
            eprintln!("PIN MISMATCH: {} [{}]", spec.name, spec.file);
            eprintln!("  PIN (hand-built):  {:?}", pin);
            eprintln!("  REGISTERED type:   {:?}", c.type_);
            failures.push(format!(
                "{}: `{}` registered type is NOT def-eq to its hand-built pin",
                spec.file, spec.name
            ));
        }
    }

    println!(
        "{pinned_statements} statements pinned (raw-Expr, elaborator-free); {} flagships \
         unpinned: {flagships_unpinned:?}",
        flagships_unpinned.len()
    );
    println!(
        "plus {pinned_aux} auxiliary shape pins (Reach type+constructors per declaring file; \
         SetMaskSound.mem type)"
    );

    assert!(
        failures.is_empty(),
        "{} statement pin(s) FAILED:\n  {}",
        failures.len(),
        failures.join("\n  ")
    );
    assert!(
        flagships_unpinned.is_empty(),
        "flagship statement(s) unpinned: {flagships_unpinned:?}"
    );
}

