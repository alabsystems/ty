// ═══════════════════════════════════════════════════════════════════════════════════════════
// Raw-constructor helpers. NOTHING here touches clean's parser or elaborator: only the kernel
// Expr constructors. `v(i)` is de Bruijn (0 = innermost binder); every binder is explicit
// (`BinderInfo::Default`), matching how clean registers parenthesized surface binders.
// ═══════════════════════════════════════════════════════════════════════════════════════════

fn v(i: u32) -> Expr {
    Expr::bvar(i)
}
fn pi(ty: Expr, body: Expr) -> Expr {
    Expr::pi(BinderInfo::Default, ty, body)
}
fn lam(ty: Expr, body: Expr) -> Expr {
    Expr::lam(BinderInfo::Default, ty, body)
}
/// Non-dependent arrow `a -> b` (still a Pi; the codomain must be indexed as if under one
/// extra anonymous binder).
fn arr(a: Expr, b: Expr) -> Expr {
    Expr::arrow(a, b)
}
fn app(f: Expr, x: Expr) -> Expr {
    Expr::app(f, x)
}
fn apps<const N: usize>(f: Expr, args: [Expr; N]) -> Expr {
    Expr::apps(f, args)
}
/// Constant with NO universe levels (level-monomorphic).
fn cn(name: &str) -> Expr {
    Expr::const_str(name)
}
/// Constant with explicit universe levels.
fn cl(name: &str, levels: Vec<Level>) -> Expr {
    Expr::const_str_levels(name, levels)
}
fn l0() -> Level {
    Level::zero()
}
fn l1() -> Level {
    Level::succ(Level::zero())
}
fn prop() -> Expr {
    Expr::prop()
}
/// `Type` (= Sort 1), the universe of the quantified state spaces.
fn type0() -> Expr {
    Expr::type_()
}
fn nat() -> Expr {
    cn("Nat")
}
fn bool_() -> Expr {
    cn("Bool")
}
fn false_() -> Expr {
    cn("False")
}
/// `List.{0} t` — the statements only ever instantiate `List` at `Type 0` elements.
fn list0(t: Expr) -> Expr {
    app(cl("List", vec![l0()]), t)
}
fn list_nat() -> Expr {
    list0(nat())
}
/// `Prod.{0,0} Nat Nat` — the lexicographic measure's pair type.
fn prod_nn() -> Expr {
    apps(cl("Prod", vec![l0(), l0()]), [nat(), nat()])
}
/// `@Eq.{1} t a b` — every statement equality is at a `Type 0` carrier (Nat / Bool / List Nat
/// / a quantified `State : Type`), i.e. `Sort 1`, so the level is always `1`.
fn eq1(t: Expr, a: Expr, b: Expr) -> Expr {
    apps(cl("Eq", vec![l1()]), [t, a, b])
}
fn and(a: Expr, b: Expr) -> Expr {
    apps(cn("And"), [a, b])
}
fn or(a: Expr, b: Expr) -> Expr {
    apps(cn("Or"), [a, b])
}
fn iff(a: Expr, b: Expr) -> Expr {
    apps(cn("Iff"), [a, b])
}
fn nat_lt(a: Expr, b: Expr) -> Expr {
    apps(cn("Nat.lt"), [a, b])
}
/// `@List.length.{0} t l`.
fn len0(t: Expr, l: Expr) -> Expr {
    apps(cl("List.length", vec![l0()]), [t, l])
}

