//! STATEMENT PINS — closing the statement-translation trust residual for the clean-kernel
//! soundness proofs (`proofs/clean/*.clean`, kernel-checked by `clean_soundness_proofs.rs`).
//!
//! ## The residual this closes
//!
//! The clean CIC kernel verifies each proof against the ELABORATED statement. If clean's
//! ELABORATOR mistranslated the surface statement (wrong binder structure, wrong de Bruijn
//! index, wrong universe level, wrong constant), the kernel would faithfully check the WRONG
//! proposition — a false trust label the kernel itself cannot catch. This test removes the
//! elaborator from that loop for the pinned statements: each pin is the kernel `Expr` of the
//! SURFACE statement, HAND-BUILT from raw constructors (`Expr::pi` / `Expr::app` /
//! `Expr::bvar` / `Expr::const_` / `Expr::sort` — **no parser, no elaborator, anywhere in pin
//! construction**), and asserted **definitionally equal** (`TypeChecker::is_def_eq`, the
//! kernel's own judgment) to the type the elaborator registered. The proof files are parsed +
//! elaborated ONLY to obtain the registered constants — the registered type is the object
//! under test, never an input to a pin.
//!
//! ## What the pins remove from the TCB
//!
//!   - clean-elaborator statement translation for every pinned theorem: binder order and
//!     count, de Bruijn structure, universe levels (`Eq.{1}`, `List.{0}`, `Prod.{0,0}`,
//!     `ite.{1}`), and every constant reference in the statement.
//!   - the `Reach` inductive's SHAPE in each file that declares it: the type former AND both
//!     constructor types (`Reach`, `Reach.base`, `Reach.step`) are pinned, so the reachability
//!     predicate quantified over by `reach_least` / `d3_step_simulation` /
//!     `refinement_safety_transfer` / `refinement_transitivity` means base-or-step exactly.
//!     (The recursor is generated by the KERNEL from these, not by the elaborator.)
//!   - `SetMaskSound.mem`'s defining BODY (`fun (m i : Nat) => Nat.testBit m i`): pinned as a
//!     VALUE pin, so `mask_injective`'s statement bottoms out in the prelude's `Nat.testBit`
//!     with no file-local elaborated definition left in its trust chain.
//!
//! ## What REMAINS elaborator-translated (honest residual)
//!
//!   - Bodies of the other referenced file-local DEFS. A pinned statement that cites such a
//!     def is pinned only DOWN TO that def's name; its body is still elaborator-trusted:
//!     `PackInj.{AllLt, baseValue}`, `MixedRadixInj.{DigitsLt, mrEnc}`,
//!     `L1Cover.{AllLt, baseValue}`, `L1bMixed.{AllDigitLt, mixedRadix, radProduct}`,
//!     `LexLive.lexLt`, `ColCard.rangeList`, `TupleCount.{allTuples, prod}`, and R1's
//!     `memberOf` / `listExistsBeq`. (Each has `rfl` reduction-sanity theorems in its file,
//!     which constrain — but do not fully pin — the elaborated body.)
//!   - The PRELUDE constants the statements cite (`Eq`, `And`, `Or`, `Iff`, `False`, `Nat.*`,
//!     `List.length`, `Prod`, `Bool.*`, `ite`, `instDecidableEqBool`): their definitions come
//!     from `Environment::with_prelude()`, part of clean's kernel trust anchor — not per-file
//!     elaboration, but trusted nonetheless.
//!   - K2's `if c then a else b` SUGAR: the pin fixes the standard desugaring
//!     `@ite.{1} Nat (c = Bool.true) (instDecidableEqBool c Bool.true) a b` — i.e. the
//!     Decidable-instance form is part of the pinned statement (any change to the desugaring
//!     fails the pin loudly, which is the point).
//!   - `is_def_eq` itself is kernel code: a pin certifies the registered type is
//!     DEFINITIONALLY the hand-built statement, on the kernel's judgment.
//!
//! ## Negative controls
//!
//! Three deliberately WRONG pins prove the comparison can fail: a `reach_least` pin whose
//! conclusion is `Init s` instead of `R s`; a `reach_least` pin with `hstep`'s hypotheses
//! swapped; and a correct `mask_injective` pin compared against a DIFFERENT theorem's type.

