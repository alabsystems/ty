/// Elaborate one `.clean` proof file into a fresh prelude environment (the exact
/// `clean check` pipeline; same load pattern as `clean_soundness_proofs.rs`).
fn load_env(file: &str) -> Environment {
    let path = proofs_dir().join(file);
    let src =
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let mut env = Environment::with_prelude();
    let mut fc = FileContext::new();
    let decls = parse_file(&src).unwrap_or_else(|e| panic!("{file}: parse error: {e:?}"));
    for d in &decls {
        let p = preprocess_decl_with_context(d, &mut fc);
        elaborate_decl_and_register(&mut env, &p)
            .unwrap_or_else(|e| panic!("{file}: elaboration failed: {e}"));
    }
    env
}

