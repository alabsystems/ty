    #[test]
    fn canonicalized_successors_do_not_mutate_parent_marking() {
        let net = symmetric_sink_net();
        let setup = ExplorationSetup::analyze(&net);
        let por_strategy = PorStrategy::None;
        let canonicalizer = super::super::symmetry::PetriCanonicalizer::build(&net);
        assert!(!canonicalizer.is_empty());
        let mut provider = InterpretedSuccessorProvider::new(
            &net,
            &setup.marking_config,
            setup.pack_capacity,
            setup.num_transitions,
            None,
            &por_strategy,
            Some(canonicalizer),
        );
        let mut current_marking = net.initial_marking.clone();
        let mut observed = Vec::new();

        let completed = provider.for_each_successor(&mut current_marking, &mut |successor| {
            observed.push((successor.transition, successor.marking.to_vec()));
            SuccessorVisit::Continue
        });

        assert!(completed);
        assert_eq!(current_marking, net.initial_marking);
        assert_eq!(
            observed,
            vec![
                (TransitionIdx(0), vec![0, 1, 1]),
                (TransitionIdx(1), vec![0, 1, 1]),
            ]
        );
    }
